/**
 * Question bank CLI.
 *
 *   bun scripts/bank.ts validate <file.json>...      Validate batch files locally (no network). Exit 1 on any error.
 *   bun scripts/bank.ts seed                         Rebuild content/bank/seed-batch-001.json from src/content/bank/seed.ts.
 *   bun scripts/bank.ts taxonomy-sql                 Regenerate the taxonomy migration from src/content/bank/taxonomy.ts.
 *   bun scripts/bank.ts coverage [file.json]...      Coverage by question type for local files (live coverage is in /staff).
 *   bun scripts/bank.ts import <file.json> [--commit] Send a batch to the bank-import edge function. Dry run unless --commit.
 *                                                    Needs HOW_STAFF_EMAIL and HOW_STAFF_PASSWORD (a reviewer or author account).
 *   bun scripts/bank.ts export [status]              Download questions (default: published) as JSON. Same credentials.
 *
 * A batch file is { "batch_id": "...", "questions": BankQuestion[] }. See docs/question-bank.md.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { validateBatch, VALIDATOR_VERSION } from '../src/content/bank/validate';
import { buildSeedBatch, BATCH_ID } from '../src/content/bank/seed';
import { LEARNING_PATHS, QUESTION_TYPES } from '../src/content/bank/taxonomy';
import type { BankQuestion } from '../src/content/bank/schema';

const [, , cmd, ...args] = process.argv;
const SUPABASE_URL = process.env.VITE_SUPABASE_URL || 'https://ahokskmczlkhsppzqcuk.supabase.co';
const KEY = process.env.VITE_SUPABASE_PUBLISHABLE_KEY || 'sb_publishable_dYPYOiF16QVPAvaUDVgWdQ_bZ75d5o-';

const load = (f: string): { batch_id: string; questions: BankQuestion[] } => {
  const j = JSON.parse(readFileSync(f, 'utf8'));
  return Array.isArray(j) ? { batch_id: f, questions: j } : j;
};

function printReport(file: string, qs: BankQuestion[]) {
  const r = validateBatch(qs);
  let errors = 0;
  for (const rep of r.reports) {
    const errs = rep.issues.filter((i) => i.severity === 'error');
    const warns = rep.issues.filter((i) => i.severity === 'warning');
    errors += errs.length;
    const tag = errs.length ? 'FAIL' : 'ok  ';
    console.log(`${tag} ${rep.question}@${rep.version}${rep.needs_semantic_review ? '  (needs semantic review)' : ''}`);
    for (const i of [...errs, ...warns]) console.log(`       ${i.severity}: ${i.path}  ${i.rule}`);
  }
  for (const i of r.batchIssues) { console.log(`batch ${i.severity}: ${i.question} ${i.path} ${i.rule}`); if (i.severity === 'error') errors++; }
  console.log(`\n${file}: ${qs.length} questions, ${errors} errors, validator ${VALIDATOR_VERSION}`);
  return { ...r, errors };
}

async function staffToken() {
  const email = process.env.HOW_STAFF_EMAIL;
  const password = process.env.HOW_STAFF_PASSWORD;
  if (!email || !password) throw new Error('Set HOW_STAFF_EMAIL and HOW_STAFF_PASSWORD');
  const res = await fetch(`${SUPABASE_URL}/auth/v1/token?grant_type=password`, { method: 'POST', headers: { apikey: KEY, 'content-type': 'application/json' }, body: JSON.stringify({ email, password }) });
  if (!res.ok) throw new Error(`sign-in failed: ${res.status} ${await res.text()}`);
  return (await res.json()).access_token as string;
}

const sqlStr = (s: string) => `'${s.replace(/'/g, "''")}'`;

async function main() {
  if (cmd === 'validate') {
    let bad = 0;
    for (const f of args) bad += printReport(f, load(f).questions).errors;
    process.exit(bad ? 1 : 0);
  }
  if (cmd === 'seed') {
    const questions = buildSeedBatch();
    const r = printReport(BATCH_ID, questions);
    if (r.errors) process.exit(1);
    mkdirSync('content/bank', { recursive: true });
    const body = JSON.stringify({ batch_id: BATCH_ID, questions, reports: r.reports }, null, 2) + '\n';
    writeFileSync(`content/bank/${BATCH_ID}.json`, body);
    console.log(`wrote content/bank/${BATCH_ID}.json sha256=${createHash('sha256').update(body).digest('hex')}`);
    return;
  }
  if (cmd === 'taxonomy-sql') {
    const out: string[] = ['-- Generated by `bun scripts/bank.ts taxonomy-sql` from src/content/bank/taxonomy.ts. Do not edit by hand.', ''];
    QUESTION_TYPES.forEach((t, i) => out.push(
      `insert into public.question_types (id, title, domain, definition, excludes, engine, target, age_bands, difficulty_bands, acceptance, sort) values (${[t.id, t.title, t.domain, t.definition, t.excludes, t.engine].map(sqlStr).join(', ')}, ${t.target}, ${sqlStr(`{${t.ageBands.join(',')}}`)}, ${sqlStr(`{${t.difficultyBands.join(',')}}`)}, ${sqlStr(JSON.stringify(t.acceptance))}::jsonb, ${i})\n  on conflict (id) do update set title = excluded.title, domain = excluded.domain, definition = excluded.definition, excludes = excluded.excludes, engine = excluded.engine, target = excluded.target, age_bands = excluded.age_bands, difficulty_bands = excluded.difficulty_bands, acceptance = excluded.acceptance, sort = excluded.sort;`));
    LEARNING_PATHS.forEach((p, pi) => {
      out.push(`insert into public.learning_paths (id, title, kind, description, sort) values (${[p.id, p.title, p.kind, p.description].map(sqlStr).join(', ')}, ${pi}) on conflict (id) do update set title = excluded.title, kind = excluded.kind, description = excluded.description, sort = excluded.sort;`);
      p.sections.forEach((s, si) => {
        out.push(`insert into public.curriculum_sections (id, path_id, title, sort) values (${[s.id, p.id, s.title].map(sqlStr).join(', ')}, ${si}) on conflict (id) do update set title = excluded.title, sort = excluded.sort;`);
        s.topics.forEach((t, ti) => {
          out.push(`insert into public.curriculum_topics (id, section_id, path_id, title, sort) values (${[t.id, s.id, p.id, t.title].map(sqlStr).join(', ')}, ${ti}) on conflict (id) do update set title = excluded.title, sort = excluded.sort;`);
          for (const ty of t.types) out.push(`insert into public.topic_question_types (topic_id, type_id) values (${sqlStr(t.id)}, ${sqlStr(ty)}) on conflict do nothing;`);
        });
      });
    });
    writeFileSync('supabase/migrations/20261024000006_bank_taxonomy.sql', out.join('\n') + '\n');
    console.log(`wrote taxonomy: ${QUESTION_TYPES.length} types, ${LEARNING_PATHS.length} paths`);
    return;
  }
  if (cmd === 'coverage') {
    const files = args.length ? args : [`content/bank/${BATCH_ID}.json`];
    const qs = files.flatMap((f) => load(f).questions);
    console.log('type'.padEnd(28), 'engine'.padEnd(10), 'in files', 'target');
    for (const t of QUESTION_TYPES) console.log(t.id.padEnd(28), t.engine.padEnd(10), String(qs.filter((q) => q.question_type === t.id).length).padStart(8), String(t.target).padStart(6));
    console.log(`\ntotal ${qs.length} of ${QUESTION_TYPES.reduce((s, t) => s + t.target, 0)} planned`);
    return;
  }
  if (cmd === 'import') {
    const file = args.find((a) => !a.startsWith('--'));
    if (!file) throw new Error('usage: import <file.json> [--commit]');
    const b = load(file);
    const local = printReport(file, b.questions);
    if (local.errors) console.log('\nLocal validation failed. The server will store failing items as validation_failed.');
    const token = await staffToken();
    const res = await fetch(`${SUPABASE_URL}/functions/v1/bank-import`, {
      method: 'POST', headers: { apikey: KEY, authorization: `Bearer ${token}`, 'content-type': 'application/json' },
      body: JSON.stringify({ batch_id: b.batch_id, questions: b.questions, dry_run: !args.includes('--commit') }),
    });
    console.log(res.status, JSON.stringify(await res.json(), null, 2));
    process.exit(res.ok ? 0 : 1);
  }
  if (cmd === 'export') {
    const token = await staffToken();
    const res = await fetch(`${SUPABASE_URL}/rest/v1/rpc/staff_export`, { method: 'POST', headers: { apikey: KEY, authorization: `Bearer ${token}`, 'content-type': 'application/json' }, body: JSON.stringify({ p_status: args[0] ?? 'published' }) });
    if (!res.ok) throw new Error(`${res.status} ${await res.text()}`);
    const questions = await res.json();
    const f = `content/bank/export-${args[0] ?? 'published'}.json`;
    writeFileSync(f, JSON.stringify({ batch_id: `export-${new Date().toISOString().slice(0, 10)}`, questions }, null, 2) + '\n');
    console.log(`wrote ${f} (${questions.length} questions)`);
    return;
  }
  console.log(readFileSync(new URL(import.meta.url), 'utf8').split('*/')[0]);
}

main().catch((e) => { console.error(e.message ?? e); process.exit(1); });
