/**
 * Generates supabase/seed/content.sql from the TypeScript content source.
 * Run: bun scripts/generate-seed.ts
 * Content is validated first; the database trigger re-validates on publish.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { ALL_CONTENT, SKILLS, validateActivity } from '../src/content/index';

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const arr = (xs: string[]) => `array[${xs.map(q).join(',')}]::text[]`;
const js = (v: unknown) => `${q(JSON.stringify(v))}::jsonb`;

const problems = ALL_CONTENT.flatMap((a) => validateActivity(a).map((e) => `${a.id}: ${e}`));
if (problems.length) {
  console.error(problems.join('\n'));
  process.exit(1);
}

const out: string[] = ['-- Generated by scripts/generate-seed.ts. Do not edit by hand.', 'begin;'];
for (const s of SKILLS) {
  out.push(
    `insert into public.skills (id, domain, title, description, prerequisites, assessment_tags, sort_order) values (${q(s.id)}, ${q(s.domain)}, ${q(s.title)}, ${q(s.description)}, ${arr(s.prerequisites)}, ${arr(s.assessment_tags)}, ${s.sort_order}) on conflict (id) do update set domain = excluded.domain, title = excluded.title, description = excluded.description, prerequisites = excluded.prerequisites, assessment_tags = excluded.assessment_tags, sort_order = excluded.sort_order;`,
  );
}
for (const a of ALL_CONTENT) {
  out.push(
    `insert into public.activities (id, content_version, title, domain, skill_id, subskills, assessment_tags, mode, activity_type, age_min, age_max, prerequisites, difficulty, payload, answer_key, accessibility_metadata, review_status, reviewed_by, reviewed_at) values (${q(a.id)}, ${a.content_version}, ${q(a.title)}, ${q(a.domain)}, ${q(a.skill_id)}, ${arr(a.subskills)}, ${arr(a.assessment_tags)}, ${q(a.mode)}, ${q(a.activity_type)}, ${a.age_min}, ${a.age_max}, ${arr(a.prerequisites)}, ${js(a.difficulty)}, ${js(a.payload)}, ${js(a.answer_key)}, ${js(a.accessibility_metadata)}, ${q(a.review_status)}, ${a.reviewed_by ? q(a.reviewed_by) : 'null'}, ${a.reviewed_by ? 'now()' : 'null'}) on conflict (id, content_version) do nothing;`,
  );
}
out.push('commit;');
mkdirSync('supabase/seed', { recursive: true });
writeFileSync('supabase/seed/content.sql', out.join('\n') + '\n');
console.log(`Wrote ${SKILLS.length} skills and ${ALL_CONTENT.length} activities to supabase/seed/content.sql`);

// JSON form, for loading through pg_net when the SQL file is too large to paste.
writeFileSync('supabase/seed/content.json', JSON.stringify({ skills: SKILLS, activities: ALL_CONTENT }));
console.log('Wrote supabase/seed/content.json');
